import fs from 'node:fs/promises';
import path from 'node:path';
import { chromium, expect } from '@playwright/test';
import { browserLaunchOptions } from './browser-options.mjs';
import { openPreviewExport } from './preview-export-controls.mjs';
import JSZip from 'jszip';

const temp = path.resolve('.tmp', `compression-auto-${Date.now()}`);
await fs.mkdir(temp, { recursive: true });
const browser = await chromium.launch({ ...browserLaunchOptions(), headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, acceptDownloads: true });
const panel = page.locator('#step-7');
const errors = [];
page.on('pageerror', error => errors.push(error.message));
const loaded = count => expect(panel.locator('.compression-source-copy > strong')).toHaveText(`${count} 帧已载入`);
const generate = () => panel.getByRole('button', { name: /^生成对比/ });
try {
  await page.goto(process.env.FRAMECRAFT_URL || 'http://127.0.0.1:8765');
  const cards = page.locator('#step-3 .frame-card');
  await expect(cards.first()).toBeVisible();
  const count = await cards.count();
  await loaded(count);
  await expect.poll(() => panel.locator('.compression-metrics').getAttribute('data-input-bytes')).not.toBe('0');
  await page.getByRole('button', { name: '奇数帧', exact: true }).click();
  const selectedCount = Math.ceil(count / 2);
  await loaded(selectedCount);
  await expect(generate()).toBeEnabled();
  await page.locator('#step-3').getByRole('spinbutton', { name: '动画预览帧率', exact: true }).fill('18');
  await expect(panel.locator('#compression-fps')).toHaveValue('18');
  await generate().click();
  await expect(panel.locator('.compression-thumbnail')).toHaveCount(selectedCount);
  await expect(generate()).toBeEnabled();
  await cards.first().locator('input').uncheck();
  await loaded(selectedCount - 1);
  await expect(panel.locator('.compression-output-image')).toHaveCount(0);
  const downloading = page.waitForEvent('download');
  await (await openPreviewExport(page, 'original', 'frames')).click();
  const download = await downloading;
  const output = path.join(temp, 'selected.zip');
  await download.saveAs(output);
  const zip = await JSZip.loadAsync(await fs.readFile(output));
  const manifest = JSON.parse(await zip.file('manifest.json').async('string'));
  expect(manifest.frames).toHaveLength(selectedCount - 1);
  expect(manifest.fps).toBe(18);
  await page.getByRole('button', { name: '全不选', exact: true }).click();
  await expect(panel.locator('.compression-metrics')).toHaveAttribute('data-frame-count', '0');
  await expect(generate()).toBeDisabled();
  await page.getByRole('button', { name: '全选', exact: true }).click();
  await loaded(count);
  const fixture = await page.evaluate(() => {
    const canvas = document.createElement('canvas'); canvas.width = 32; canvas.height = 48;
    const ctx = canvas.getContext('2d'); ctx.fillStyle = '#c05030'; ctx.fillRect(4, 4, 24, 40);
    return canvas.toDataURL().split(',')[1];
  });
  await panel.locator('input[type="file"]').first().setInputFiles({ name: 'local.png', mimeType: 'image/png', buffer: Buffer.from(fixture, 'base64') });
  await loaded(1);
  await page.getByRole('button', { name: '奇数帧', exact: true }).click();
  await loaded(1);
  await expect(panel.locator('.compression-source-copy')).toContainText('local.png');
  const save = async name => {
    await page.locator('#animation-name').fill(name);
    await page.getByRole('textbox', { name: '项目目录', exact: true }).fill(temp);
    const waiting = page.waitForResponse(response => response.request().method() === 'POST' && response.url().includes('/api/projects'));
    await page.getByRole('button', { name: '添加到帧动画项目列表', exact: true }).click();
    const response = await waiting;
    expect(response.ok(), await response.text()).toBe(true);
    return response.json();
  };
  const reopen = async name => {
    await page.getByRole('button', { name: '清空当前素材', exact: true }).click();
    await page.locator('.project-library').getByRole('button', { name: `打开项目 ${name}`, exact: true }).click();
    await expect(page.locator('#animation-name')).toHaveValue(name);
  };
  const localProject = await save('compression_local');
  expect(JSON.parse(await fs.readFile(path.join(localProject.path, 'project.json'), 'utf8')).compression.sourceMode).toBe('local');
  await reopen('compression_local');
  await loaded(1);
  await page.getByRole('button', { name: '全选', exact: true }).click();
  await loaded(1);
  await panel.getByRole('button', { name: /使用已选帧/ }).click();
  await loaded(count);
  const before = await panel.locator('.compression-thumbnail').evaluateAll(nodes => nodes.map(node => node.title));
  await page.getByRole('button', { name: '反转顺序', exact: true }).click();
  await expect.poll(() => panel.locator('.compression-thumbnail').evaluateAll(nodes => nodes.map(node => node.title))).toEqual(before.reverse());
  await expect(generate()).toBeEnabled();
  await generate().click();
  await expect(panel.locator('.compression-output-image')).toBeVisible();
  await expect(generate()).toBeEnabled();
  const workspaceProject = await save('compression_workspace');
  expect(JSON.parse(await fs.readFile(path.join(workspaceProject.path, 'project.json'), 'utf8')).compression.sourceMode).toBe('workbench');
  await reopen('compression_workspace');
  await loaded(count);
  await expect(generate()).toBeEnabled();
  await expect(panel.locator('.compression-output-image')).toBeVisible();
  await page.getByRole('button', { name: '奇数帧', exact: true }).click();
  await loaded(selectedCount);
  await expect(panel.locator('.compression-output-image')).toHaveCount(0);
  // Restoring upstream smoothing publishes new URLs after the project opens.
  // Its matching compression result must survive that publication.
  const projectPath = path.join(workspaceProject.path, 'project.json');
  const stored = JSON.parse(await fs.readFile(projectPath, 'utf8'));
  const smoothingCode = await fs.readFile('src/lib/smoothing.ts', 'utf8');
  const pipelineVersion = Number(smoothingCode.match(/SMOOTHING_PIPELINE_VERSION = (\d+)/)[1]);
  stored.smoothing = { enabled: true, pipelineVersion, options: stored.workspace.options, frames: stored.frames.map((frame, i) => i === stored.frames.length - 1 ? { ...frame, file: stored.frames[0].file } : frame) };
  stored.compression.sources.at(-1).file = stored.compression.sources[0].file;
  stored.compression.results.at(-1).file = stored.compression.results[0].file;
  await fs.writeFile(projectPath, JSON.stringify(stored));
  await reopen('compression_workspace');
  await loaded(count);
  await expect(page.locator('#smoothing-enabled')).toBeChecked();
  await expect(generate()).toBeEnabled();
  await expect(panel.locator('.compression-output-image')).toBeVisible();
  // Same names and dimensions do not make a stale snapshot valid: removing
  // smoothing must reload the raw pixels and discard the old comparison.
  stored.smoothing = null;
  await fs.writeFile(projectPath, JSON.stringify(stored));
  await reopen('compression_workspace');
  await loaded(count);
  await expect(generate()).toBeEnabled();
  await expect(panel.locator('.compression-output-image')).toHaveCount(0);
  expect(errors).toEqual([]);
  console.log('PASS: step 07 auto-loads selection/order/FPS, clears stale results, exports current input, handles empty selection, preserves local imports and restores both source modes with saved comparisons.');
} finally { await browser.close(); }
