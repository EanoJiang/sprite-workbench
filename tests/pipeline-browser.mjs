import fs from 'node:fs/promises';
import path from 'node:path';
import { chromium, expect } from '@playwright/test';
import { browserLaunchOptions } from './browser-options.mjs';
import { openPreviewExport, previewExportToggle } from './preview-export-controls.mjs';
import JSZip from 'jszip';

const temp = path.resolve('.tmp', `pipeline-${Date.now()}`);
await fs.mkdir(temp, { recursive: true });
const browser = await chromium.launch({ ...browserLaunchOptions(), headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, acceptDownloads: true });
const errors = [];
page.on('pageerror', error => errors.push(error.message));
const review = page.locator('#step-3');
const matte = page.locator('#step-4');
const apply = () => matte.getByRole('button', { name: /应用抠图并继续/ });
const readPng = locator => locator.evaluate(async img => Array.from(new Uint8Array(await (await fetch(img.src)).arrayBuffer())));
const pixels = locator => locator.evaluate(async img => {
  await img.decode();
  const canvas = document.createElement('canvas'); canvas.width = img.naturalWidth; canvas.height = img.naturalHeight;
  const ctx = canvas.getContext('2d'); ctx.drawImage(img, 0, 0);
  return { width: canvas.width, height: canvas.height, corner: Array.from(ctx.getImageData(0, 0, 1, 1).data), center: Array.from(ctx.getImageData(canvas.width / 2, canvas.height / 2, 1, 1).data) };
});
let smoothingOutput;
const smoothingInputs = [];
await page.route('**/api/smoothing/status', route => route.fulfill({ json: { ready: true, model: 'pipeline-test' } }));
await page.route('**/api/smoothing/frame', route => {
  smoothingInputs.push(route.request().postDataBuffer());
  return route.fulfill({ contentType: 'image/png', body: smoothingOutput });
});
try {
  await page.goto(process.env.FRAMECRAFT_URL || 'http://127.0.0.1:5173');
  await expect(page.locator('.workspace-section > .section-heading h2')).toHaveText(['预览与截取区间', '抽帧设置', '检查帧与布局', '精细抠图', '动画帧选取与预览', 'Real-ESRGAN 平滑处理', '动画帧精度压缩']);
  const fixtures = await page.evaluate(() => ['#eb2530', '#3264e4', '#f4a600'].map((color, i) => {
    const canvas = document.createElement('canvas'); canvas.width = 64; canvas.height = 80;
    const ctx = canvas.getContext('2d'); ctx.fillStyle = '#47ca30'; ctx.fillRect(0, 0, 64, 80);
    ctx.fillStyle = color; ctx.fillRect(16, 16, 32, 48);
    return { name: `${i + 1}.png`, encoded: canvas.toDataURL().split(',')[1] };
  }));
  await expect(page.locator('#media-import-trigger')).toBeEnabled();
  await page.evaluate(items => {
    const data = new DataTransfer();
    for (const item of items) data.items.add(new File([Uint8Array.from(atob(item.encoded), c => c.charCodeAt(0))], item.name, { type: 'image/png' }));
    document.querySelector('.media-import-zone').dispatchEvent(new DragEvent('drop', { bubbles: true, cancelable: true, dataTransfer: data }));
  }, fixtures);
  await page.getByRole('dialog', { name: '为新项目命名', exact: true }).getByRole('button', { name: '确认名称', exact: true }).click();
  await expect(review.locator('.frame-card')).toHaveCount(3);
  await page.locator('#stride').fill('2');
  await page.locator('#target-height').fill('80');
  await page.locator('#padding').fill('0');
  await page.getByRole('button', { name: '开始抽帧并检查', exact: true }).click();
  await expect(review.locator('.frame-card')).toHaveCount(2);
  const before = await pixels(review.locator('.frame-thumb img').first());
  expect(before.corner).toEqual([71, 202, 48, 255]);
  expect(before.height).toBe(80);
  await expect(page.locator('#matting-status')).toHaveAttribute('data-state', 'pending');
  await review.locator('.frame-card input').last().uncheck();
  await apply().click();
  await expect(page.locator('#step-5 .sequence-frame')).toHaveCount(1);
  const mattedImage = page.locator('#step-5 .sequence-frame img').first();
  const matted = await pixels(mattedImage);
  expect(matted.corner[3]).toBe(0);
  expect(matted.center[3]).toBe(255);
  expect(matted.height).toBe(before.height);
  expect(await pixels(review.locator('.frame-thumb img').first())).toEqual(before);
  const matteBytes = Buffer.from(await readPng(mattedImage));
  await expect(previewExportToggle(page)).toBeEnabled();
  expect(Buffer.from(await readPng(page.locator('#step-7 .compression-original-image'))).equals(matteBytes)).toBe(true);
  smoothingOutput = Buffer.from(await page.evaluate(async url => {
    const img = new Image(); img.src = url; await img.decode();
    const canvas = document.createElement('canvas'); canvas.width = img.width; canvas.height = img.height;
    const ctx = canvas.getContext('2d'); ctx.drawImage(img, 0, 0); ctx.globalCompositeOperation = 'source-atop'; ctx.fillStyle = '#3255dd'; ctx.fillRect(0, 0, canvas.width, canvas.height);
    return canvas.toDataURL().split(',')[1];
  }, await mattedImage.getAttribute('src')), 'base64');
  await page.locator('#smoothing-enabled').check();
  await page.locator('#step-6').getByRole('button', { name: '开始平滑', exact: true }).click();
  await expect(page.locator('#smoothing-status')).toHaveAttribute('data-state', 'ready');
  await expect(previewExportToggle(page)).toBeEnabled();
  expect(smoothingInputs).toHaveLength(1);
  expect(smoothingInputs[0].includes(matteBytes)).toBe(true);
  expect(Buffer.from(await readPng(page.locator('#step-7 .compression-original-image'))).equals(smoothingOutput)).toBe(true);
  expect(Buffer.from(await readPng(mattedImage)).equals(matteBytes)).toBe(true);
  expect(await pixels(review.locator('.frame-thumb img').first())).toEqual(before);
  const downloading = page.waitForEvent('download');
  await (await openPreviewExport(page, 'original', 'frames')).click();
  const download = await downloading;
  const zipFile = path.join(temp, 'final.zip'); await download.saveAs(zipFile);
  const zip = await JSZip.loadAsync(await fs.readFile(zipFile));
  const manifest = JSON.parse(await zip.file('manifest.json').async('string'));
  expect(manifest.frames).toHaveLength(1);
  expect((await zip.file(manifest.frames[0].filename).async('nodebuffer')).equals(smoothingOutput)).toBe(true);
  console.log('PASS: matte and smoothing outputs reach export without changing upstream previews.');
  await page.locator('#smoothing-enabled').uncheck();
  await page.getByRole('button', { name: '全选', exact: true }).click();
  await expect(page.locator('#matting-status')).toHaveAttribute('data-state', 'pending');
  await expect(page.locator('#step-5 .sequence-frame')).toHaveCount(0);
  await expect(previewExportToggle(page)).toBeDisabled();
  await page.locator('#padding').fill('8');
  await page.locator('#target-height').fill('96');
  await page.locator('#stride').fill('1');
  await page.getByRole('button', { name: '开始抽帧并检查', exact: true }).click();
  await expect(review.locator('.frame-card')).toHaveCount(3);
  const sampled = await pixels(review.locator('.frame-thumb img').first());
  await apply().click();
  await expect(page.locator('#step-5 .sequence-frame')).toHaveCount(3);
  const final = await pixels(page.locator('#step-5 .sequence-frame img').first());
  expect([final.width, final.height]).toEqual([sampled.width, sampled.height]);
  const ordered = await page.locator('#step-5 .sequence-frame img').evaluateAll(imgs => imgs.map(img => img.src));
  await page.getByRole('button', { name: '反转顺序', exact: true }).click();
  await expect.poll(() => page.locator('#step-5 .sequence-frame img').evaluateAll(imgs => imgs.map(img => img.src))).toEqual(ordered.reverse());
  await expect(previewExportToggle(page)).toBeEnabled();
  console.log('PASS: reselection invalidates downstream; matting preserves sampled canvas and order.');
  await page.getByRole('textbox', { name: '项目目录', exact: true }).fill(temp);
  const saving = page.waitForResponse(response => response.request().method() === 'POST' && response.url().includes('/api/projects'));
  await page.getByRole('button', { name: '添加到帧动画项目列表', exact: true }).click();
  const savedResponse = await saving; expect(savedResponse.ok(), await savedResponse.text()).toBe(true);
  const saved = await savedResponse.json();
  const stored = JSON.parse(await fs.readFile(path.join(saved.path, 'project.json'), 'utf8'));
  expect(stored.matting.frames).toHaveLength(3);
  await page.getByRole('button', { name: '清空当前素材', exact: true }).click();
  await page.locator('.project-library').getByRole('button', { name: /打开项目/ }).click();
  await expect(page.locator('#step-5 .sequence-frame')).toHaveCount(3);
  await expect(previewExportToggle(page)).toBeEnabled();
  expect((await pixels(page.locator('#step-5 .sequence-frame img').first())).corner[3]).toBe(0);
  // Stage 03 can be an independent image entry point without a source video.
  await page.getByRole('button', { name: '清空当前素材', exact: true }).click();
  const boundaries = await page.evaluate(() => [8, 4100].map(height => {
    const canvas = document.createElement('canvas'); canvas.width = 32; canvas.height = height;
    const ctx = canvas.getContext('2d'); ctx.fillStyle = 'rgba(220, 30, 40, .5)'; ctx.fillRect(0, 0, 32, height);
    return { name: `${height}.png`, encoded: canvas.toDataURL().split(',')[1] };
  }));
  await page.locator('#workbench-frames-input').setInputFiles(boundaries.map(item => ({ name: item.name, mimeType: 'image/png', buffer: Buffer.from(item.encoded, 'base64') })));
  await matte.getByRole('switch').first().uncheck();
  await matte.getByRole('checkbox', { name: '半透明像素转不透明', exact: true }).check();
  await expect(apply()).toBeEnabled();
  await apply().click();
  await expect(page.locator('#step-5 .sequence-frame')).toHaveCount(2);
  const sizes = await Promise.all([0, 1].map(i => pixels(page.locator('#step-5 .sequence-frame img').nth(i))));
  expect(sizes.map(item => [item.width, item.height, item.corner[3]])).toEqual([[32, 8, 255], [32, 4100, 255]]);
  expect(errors).toEqual([]);
  console.log('PASS: stage order 01→02→03→04→05→06→07; raw extraction, selected-only matte, downstream PNG bytes, no backward flow or repeated layout, invalidation, ordering and project restore.');
} catch (error) {
  console.error('Pipeline failure state:', await page.locator('.toast').allTextContents());
  throw error;
} finally { await browser.close(); }
