import fs from 'node:fs/promises';
import path from 'node:path';
import { chromium, expect } from '@playwright/test';
import { browserLaunchOptions } from './browser-options.mjs';

const browser = await chromium.launch({ ...browserLaunchOptions(), headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
const errors = [];
page.on('pageerror', error => errors.push(error.message));
page.setDefaultTimeout(10000);
try {
  await page.goto(process.env.FRAMECRAFT_URL || 'http://127.0.0.1:5173');
  await page.addStyleTag({ content: '* { scroll-behavior: auto !important; animation: none !important; transition: none !important; }' });
  const section = page.locator('#step-3');
  const cards = section.locator('.frame-card');
  await expect(cards.first()).toBeVisible();
  await section.getByRole('button', { name: '暂停动画', exact: true }).click();
  const thumb = cards.first().locator('.frame-thumb');
  const checkbox = cards.first().getByRole('checkbox');
  await checkbox.uncheck();
  await expect(checkbox).toBeEnabled();
  await thumb.click();
  await expect(page.locator('.inspect-modal')).toHaveCount(0);
  await expect(checkbox).toBeChecked();
  await expect(checkbox).toBeEnabled();
  await thumb.click();
  await expect(checkbox).not.toBeChecked();
  console.log('PASS left click toggles selection without inspection');

  await thumb.click({ button: 'right' });
  await expect(checkbox).not.toBeChecked();
  await expect(checkbox).toBeEnabled();
  await thumb.click();
  await expect(checkbox).toBeChecked();
  await expect(checkbox).toBeEnabled();
  await thumb.dblclick();
  await expect(page.locator('.inspect-modal')).toBeVisible();
  await expect(page.getByRole('button', { name: '取消选择此帧', exact: true })).toBeVisible();
  await page.getByRole('button', { name: '关闭帧检查', exact: true }).click();
  await checkbox.uncheck();
  await expect(checkbox).not.toBeChecked();
  await expect(checkbox).toBeEnabled();
  await thumb.dblclick();
  await expect(page.getByRole('button', { name: '选择此帧', exact: true })).toBeVisible();
  await page.getByRole('button', { name: '关闭帧检查', exact: true }).click();
  await expect(checkbox).toBeEnabled();
  await thumb.click();
  await expect(checkbox).toBeChecked();
  console.log('PASS right click leaves selection unchanged; double click preserves selection; checkbox remains independent');

  const input = section.getByRole('spinbutton', { name: '动画预览当前帧', exact: true });
  const slider = section.getByRole('slider', { name: '动画预览进度', exact: true });
  await section.getByRole('button', { name: '播放动画', exact: true }).click();
  await input.fill('8');
  await input.press('Enter');
  await expect(input).toHaveValue('8');
  await expect(slider).toHaveValue('8');
  await expect(section.locator('.animation-viewport img')).toHaveAttribute('src', await cards.nth(7).locator('img').getAttribute('src'));
  await expect(section.getByRole('button', { name: '播放动画', exact: true })).toBeVisible();
  await input.fill('999'); await input.blur();
  await expect(input).toHaveValue(String(await cards.count()));
  await input.fill('0'); await input.press('Enter');
  await expect(input).toHaveValue('1');
  await input.fill(''); await input.blur();
  await expect(input).toHaveValue('1');
  await slider.focus(); await slider.press('End');
  await expect(input).toHaveValue(String(await cards.count()));
  await expect(checkbox).toBeEnabled();
  await thumb.click();
  await expect(input).toHaveValue(String(await cards.count() - 1));
  await section.getByRole('button', { name: '全不选', exact: true }).click();
  await expect(input).toBeDisabled(); await expect(slider).toBeDisabled();
  await expect(input).toHaveValue('0');
  await expect(checkbox).toBeEnabled();
  await thumb.click();
  await expect(input).toHaveValue('1');
  await expect(input).toBeEnabled();
  console.log('PASS numeric seek, slider, pause, bounds, selection shrink, and empty sequence');

  await expect(checkbox).toBeEnabled();
  const movedId = await cards.first().getAttribute('data-frame-id');
  const targetId = await cards.nth(2).getAttribute('data-frame-id');
  await cards.first().scrollIntoViewIfNeeded();
  const from = await cards.first().boundingBox();
  const to = await cards.nth(2).boundingBox();
  await page.mouse.move(from.x + from.width / 2, from.y + from.height / 2);
  await page.mouse.down();
  await page.mouse.move(from.x + from.width / 2 + 10, from.y + from.height / 2, { steps: 5 });
  await page.mouse.move(to.x + to.width / 2, to.y + to.height / 2, { steps: 12 });
  await page.mouse.move(to.x + to.width / 2 + 1, to.y + to.height / 2);
  await page.mouse.up();
  await expect(cards.nth(1)).toHaveAttribute('data-frame-id', targetId);
  await expect(cards.nth(2)).toHaveAttribute('data-frame-id', movedId);
  await expect(cards.nth(2).getByRole('checkbox')).toBeChecked();
  await expect(input).toHaveValue('1');
  console.log('PASS pointer drag reorders frames and preserves selection');

  await fs.mkdir(path.resolve('test-results'), { recursive: true });
  await section.screenshot({ path: path.resolve('test-results/review-interaction-desktop.png') });
  await page.setViewportSize({ width: 390, height: 844 });
  await input.fill('1'); await input.press('Enter');
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await section.locator('.animation-card').screenshot({ path: path.resolve('test-results/review-interaction-mobile.png') });
  expect(errors).toEqual([]);
  console.log('PASS mobile progress controls fit; no browser errors');
} finally { await browser.close(); }
